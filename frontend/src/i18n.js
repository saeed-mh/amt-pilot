function initialLocale() {
  const savedLocale = localStorage.getItem(STORAGE_KEY)

  if (SUPPORTED_LOCALES.includes(savedLocale)) {
    return savedLocale
  }

  return navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en'
}

export const locale = ref(initialLocale())

document.documentElement.lang = locale.value

export function setLocale(nextLocale) {
  if (!SUPPORTED_LOCALES.includes(nextLocale)) {
    return
  }

  locale.value = nextLocale
  localStorage.setItem(STORAGE_KEY, nextLocale)
  document.documentElement.lang = nextLocale
}

export function t(key, variables = {}) {
  const template = messages[locale.value][key] ?? messages.en[key] ?? key

  return Object.entries(variables).reduce(
    (translation, [name, value]) => translation.replaceAll(`{${name}}`, String(value)),
    template,
  )
}

export function translateCode(namespace, code, fallback = code) {
  const key = `${namespace}.${code}`

  return messages[locale.value][key] ?? messages.en[key] ?? fallback
}

export function localizeApiError(code, fallbackMessage) {
  const key = code ? `api.${code}` : null

  if (key && messages[locale.value][key]) {
    return t(key)
  }

  return fallbackMessage || t('api.generic')
}
